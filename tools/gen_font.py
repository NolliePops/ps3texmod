def rows_to_bytes(rows):
    out = []
    for row in rows:
        v = 0
        for i, ch in enumerate(row):
            if ch == "#":
                v |= 1 << (2 - i)
        out.append(v)
    return out


def main():
    missing = [chr(c) for c in range(32, 127) if chr(c) not in GLYPHS]
    if missing:
        raise SystemExit(f"missing glyphs: {''.join(missing)!r}")
    lines = [
        "/* Generated by tools/gen_font.py - do not edit by hand. */",
        "/* 3x5 bitmap font, ASCII 32..126. One byte per row, bit 2 = left. */",
        "#ifndef PS3TEXMOD_FONT3X5_H",
        "#define PS3TEXMOD_FONT3X5_H",
        "",
        "#define FONT3X5_FIRST 32",
        "#define FONT3X5_LAST  126",
        "#define FONT3X5_W     3",
        "#define FONT3X5_H     5",
        "",
        "static const unsigned char font3x5[FONT3X5_LAST - FONT3X5_FIRST + 1][FONT3X5_H] = {",
    ]
    for c in range(32, 127):
        ch = chr(c)
        vals = rows_to_bytes(GLYPHS[ch])
        label = {"\\": "backslash", "'": "apostrophe", '"': "quote"}.get(ch, ch)
        lines.append("    {%s}, /* %3d 0x%02X %s */" % (
            ", ".join(f"0x{v:X}" for v in vals), c, c, label))
    lines += [
        "};",
        "",
        "#endif",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT, os.path.join(HERE, '..'))} "
          f"({127 - 32} glyphs)")


if __name__ == "__main__":
    main()
